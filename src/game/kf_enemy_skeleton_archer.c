/* The animate handler: as EntityAi_Animate; during animation 23 of an attack (busy bit 1), once
   blended in, SkeletonArcher_PitchPartToPlayer pitches model part 11, and otherwise work float unk48 is
   cleared. */
static void SkeletonArcher_Animate(Entity *entity) {
    f32 limits[4];
    s32 look_at_target;
    u32 blend_frames; // match: converted to float as unsigned
    EntityUnkE0 *unkE0;

    unkE0 = &entity->unkE0;
    if (ENTITY_FLAG_BITS(entity)->bit14) {
        blend_frames = entity->model->unkFC->unk88;
        if (blend_frames != 0) {
            ENTITY_FLAG_BITS(entity)->bit34 = Motion_BlendToPose(entity->model, (entity->unkC6 & 2) ? unkE0->unk40 : 1.0f / (f32)blend_frames);
        } else {
            ENTITY_FLAG_BITS(entity)->bit34 = Motion_Step(entity, ENTITY_FLAG_BITS(entity)->bits11);
        }
        if ((entity->unkC6 & 1) && entity->unkD1 == 0x17 && entity->model->unkFC->unk88 == 0) {
            SkeletonArcher_PitchPartToPlayer(entity);
        } else {
            unkE0->unk48 = 0.0f;
        }
        limits[0] = -entity->params->unk430 * 0.017453292f;
        limits[1] = entity->params->unk430 * 0.017453292f;
        limits[2] = -entity->params->unk432 * 0.017453292f;
        limits[3] = entity->params->unk432 * 0.017453292f;
        look_at_target = (s32)(entity->flags >> 9);
        if (look_at_target & 1) {
            EntityAi_LookAtPlayer(entity, unkE0->unk20, look_at_target & 1, limits, 12.0f);
        } else {
            EntityAi_LookAtPlayer(entity, unkE0->unk20, 0, NULL, 8.0f);
        }
    }
}

/* Helper of SkeletonArcher_Animate: pitches model part 11 towards the player, at most 50 degrees
   either way (work float unk48, rate 10). */
static void SkeletonArcher_PitchPartToPlayer(Entity *entity) {
    EntityModel *model = entity->model;
    EntityModelPart80 *part = &((EntityModelPart80 *)model->unkF8)[11];
    EntityUnkE0 *unkE0 = &entity->unkE0;
    f32 pitch;

    if (part != NULL) {
        pitch = EntityMath_WrapAngle(atan2(D_00413F80.position[1] - model->position[1], entity->distance_to_player));
        if (0.87266463f < pitch) {
            pitch = 0.87266463f;
        } else if (pitch < -0.87266463f) {
            pitch = -0.87266463f;
        }
        EntityMath_EaseAngleToward(&unkE0->unk48, pitch, 10.0f);
        part->unk50[0] = unkE0->unk48;
    }
}

/* The think handler: as EntityAi_Think, with SkeletonArcher_ThinkCombat for state 2. */
static void SkeletonArcher_Think(Entity *entity, s32 unknown) {
    if (D_00446ED4 % 10U == entity->unkD7 % 10U) {
        EntityAi_SensePlayer(entity, 1);
    }
    if (entity->unkC6 != 0) {
        return;
    }
    EntityAi_CheckFarFromSpawn((char *)entity);
    EntityAi_StepState(entity);
    if (ENTITY_FLAG_BITS(entity)->bit53) {
        EntityAi_ThinkReturn(entity, unknown);
        return;
    }
    switch (entity->state) {
    case 0:
        EntityAi_ThinkIdle(entity, unknown);
        return;
    case 1:
        EntityAi_ThinkPursue(entity, unknown);
        return;
    case 2:
        SkeletonArcher_ThinkCombat(entity, unknown);
        return;
    }
    EntityAi_ThinkIdle(entity, unknown);
}

/* The think function of state 2: as EntityAi_ThinkCombat, but ranged record 0 is
   SkeletonArcher_RangedAttack0 (flag bit 10 is set for a ranged attack), and closing in does not use
   func_00196D48, takes its command from EntityAi_TurnCommand where the shared one calls EntityAi_MoveCommand, and
   never runs. */
static void SkeletonArcher_ThinkCombat(Entity *entity, s32 unknown) {
    EntityUnkE0 *unkE0 = &entity->unkE0;
    f32 direction[4];
    s32 side;
    s32 turn;

    ENTITY_FLAG_BITS(entity)->bits11 = 1;
    if (EntityAi_ShouldGuard(entity, 300.0f, 0.5235988f)) {
        EntityAi_StartAction(entity, EntityAi_Guard, 1);
        return;
    }
    if (EntityAi_ShouldDodge(entity, 300.0f, 0.5235988f)) {
        EntityAi_StartAction(entity, EntityAi_Dodge, 1);
        return;
    }
    side = EntityAi_PickCombatChoice(entity, 0);
    ENTITY_FLAG_BITS(entity)->bit10 = FALSE;
    ENTITY_FLAG_BITS(entity)->bit9 = TRUE;
    if (entity->unkA0 == 0 || side == 0) {
        entity->unkCF = entity->unkCD;
        entity->unkCD = side;
        if (entity->unkCD != entity->unkCF) {
            entity->unk9E = D_00446ED4;
        }
        EntityAi_LowerChoiceWeight(entity, side);
        switch (entity->unkCD) {
        case 0:
            if (EntityAi_PickAttack((char *)entity)) {
                ENTITY_FLAG_BITS(entity)->bit10 = TRUE;
                if (ENTITY_FLAG_BITS(entity)->bits58 == 0) {
                    EntityAi_StartAction(entity, SkeletonArcher_RangedAttack0, unknown);
                } else {
                    EntityAi_StartAction(entity, EntityAi_RangedAttack, unknown);
                }
            } else {
                EntityAi_StartAction(entity, EntityAi_MeleeAttack, unknown);
            }
            return;
        case 1:
            entity->target = &D_00413F80;
            entity->unkA0 = rand() % 60 + 120;
            unkE0->unk78 = 0;
            break;
        case 2:
            entity->unkA0 = rand() % 30 + 30;
            unkE0->unk78 = -1;
            break;
        default:
            unkE0->unk78 = -1;
            break;
        }
    }
    if (unkE0->unk78 == 0) {
        turn = EntityAi_TurnFromPush(entity, direction);
        if (turn > 0) {
            entity->unkC8 = 0x201;
        } else if (turn < 0) {
            entity->unkC8 = 0x101;
        } else {
            entity->unkC8 = EntityAi_TurnCommand(entity);
        }
    }
    EntityAi_StartAction(entity, (void (*)(Entity *))unkE0->move, unknown);
}

/* The ranged attack with record 0 (busy bit 1): animation 23, as EntityAi_RangedAttack; from frame
   31 to 41 it also calls EntityAi_SpawnBoneEffect with 0x3ED and 8. */
